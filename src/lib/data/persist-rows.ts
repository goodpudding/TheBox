/**
 * Bundle row → database row, one mapping per table. The save path runs each
 * mapping on the row as loaded and on the row as it is now, and sends only the
 * columns that differ.
 */

/** A database row as the Prisma client takes it: scalars, nulls and Dates. */
export type PersistRow = { id: string } & Record<string, unknown>;

type BundleRow<K extends ArrayKey> = NonNullable<MockFixtureBundle[K]>[number];

export type PersistTable = {
  key: ArrayKey;
  /** Prisma delegate name. */
  model: string;
  /** Skip the table when this delegate is missing (client behind the schema). */
  onlyIf?: string;
  /** `now` stands in for a missing createdAt/updatedAt. */
  toRow: (row: never, now: Date) => PersistRow;
};

function table<K extends ArrayKey>(
  key: K,
  model: string,
  toRow: (row: BundleRow<K>, now: Date) => PersistRow,
  onlyIf?: string,
): PersistTable {
  return { key, model, onlyIf, toRow: toRow as PersistTable["toRow"] };
}

function jsonArr(value: unknown): string {
  return JSON.stringify(value ?? []);
}

function asDate(iso: string | null | undefined): Date | null {
  if (!iso) return null;
  return new Date(iso);
}

